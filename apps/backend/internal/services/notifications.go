// NotificationMetadata stores additional notification info
type NotificationMetadata struct {
	WebsiteURL   string `json:"websiteUrl,omitempty"`
	WebsiteName  string `json:"websiteName,omitempty"`
	IncidentType string `json:"incidentType,omitempty"`
	Status       string `json:"status,omitempty"`
	Latency      int    `json:"latency,omitempty"`
	Timestamp    string `json:"timestamp,omitempty"`
}

// NewSESEmailService creates a new SES email service
func NewSESEmailService() (*SESEmailService, error) {
	cfg, err := config.LoadDefaultConfig(context.Background())
	if err != nil {
		return nil, errors.New("failed to load AWS config")
	}

	client := ses.NewFromConfig(cfg)
	sender := os.Getenv("AWS_SES_SENDER_EMAIL")

	if sender == "" {
		return nil, errors.New("AWS_SES_SENDER_EMAIL environment variable not set")
	}

	return &SESEmailService{
		client: client,
		sender: sender,
	}, nil
}

// SendEmail sends an email notification
func (s *SESEmailService) SendEmail(ctx context.Context, toEmail, subject, htmlBody string) error {
	input := &ses.SendEmailInput{
		Source: aws.String(s.sender),
		Destination: &types.Destination{
			ToAddresses: []string{toEmail},
		},
		Message: &types.Message{
			Subject: &types.Content{
				Data: aws.String(subject),
			},
			Body: &types.Body{
				Html: &types.Content{
					Data: aws.String(htmlBody),
				},
			},
		},
	}

	result, err := s.client.SendEmail(ctx, input)
	if err != nil {
		return fmt.Errorf("failed to send email: %w", err)
	}

	if result == nil {
		return errors.New("send email returned nil result")
	}

	return nil
}

// SendWebsiteDownAlertEmail sends an email when a website goes down
