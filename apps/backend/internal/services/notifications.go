// SendWebsiteNotificationToUser sends both email and push notification to user
func SendWebsiteNotificationToUser(ctx context.Context, database *db.PrismaClient, userID, websiteID string, notificationType string, metadata NotificationMetadata) error {
	// Get user
	user, err := GetUserByID(ctx, database, userID)
	if err != nil {
		return err
	}

	// Get website
	website, err := GetWebsiteByID(ctx, database, websiteID)
	if err != nil {
		return err
	}

	// Store notification in database
	metadataJSON, _ := json.Marshal(metadata)

	_, err = database.Notification.CreateOne(
		db.Notification.User.Link(db.User.ID.Equals(userID)),
		db.Notification.Website.Link(db.Website.ID.Equals(websiteID)),
		db.Notification.Message.Set(fmt.Sprintf("Website %s is %s", website.WebsiteName, notificationType)),
		db.Notification.Metadata.Set(metadataJSON),
		db.Notification.Status.Set(db.NotficationStatusPending),
	).Exec(ctx)

	if err != nil {
		return err
	}

	// Send email notification
	emailService, err := NewSESEmailService()
	if err == nil {
		if notificationType == "down" {
			emailService.SendWebsiteDownAlertEmail(ctx, user.Email, website.WebsiteName, website.URL)
		} else if notificationType == "up" {
			emailService.SendWebsiteBackUpEmail(ctx, user.Email, website.WebsiteName, website.URL)
		}
	}

	return nil
}

// GetWebsiteByID retrieves website by ID
func GetWebsiteByID(ctx context.Context, database *db.PrismaClient, websiteID string) (*db.WebsiteModel, error) {
	website, err := database.Website.FindUnique(db.Website.ID.Equals(websiteID)).Exec(ctx)
	if err != nil {
		return nil, errors.New("website not found")
	}

	return website, nil
}

// UpdateNotificationStatus updates notification status
func UpdateNotificationStatus(ctx context.Context, database *db.PrismaClient, notificationID, status string) error {
	statusEnum, err := parseNotificationStatus(status)
	if err != nil {
		return err
	}

	_, err = database.Notification.FindUnique(db.Notification.ID.Equals(notificationID)).Update(
		db.Notification.Status.Set(statusEnum),
	).Exec(ctx)

	return err
}

func parseNotificationStatus(status string) (db.NotficationStatus, error) {
	switch strings.ToLower(status) {
	case strings.ToLower(string(db.NotficationStatusPending)):
		return db.NotficationStatusPending, nil
	case strings.ToLower(string(db.NotficationStatusSent)):
		return db.NotficationStatusSent, nil
	case strings.ToLower(string(db.NotficationStatusFailed)):
		return db.NotficationStatusFailed, nil
	default:
		return "", fmt.Errorf("invalid notification status: %s", status)
	}
}

// GetUserNotifications retrieves all notifications for a user
func GetUserNotifications(ctx context.Context, database *db.PrismaClient, userID string, limit int) ([]db.NotificationModel, error) {
	notifications, err := database.Notification.FindMany(
		db.Notification.UserID.Equals(userID),
	).OrderBy(
		db.Notification.CreatedAt.Order("desc"),
	).Take(limit).Exec(ctx)

	if err != nil {
		return nil, err
	}

	return notifications, nil
}
